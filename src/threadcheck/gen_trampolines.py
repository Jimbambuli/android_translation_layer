#!/usr/bin/env python3
# gen_trampolines.py OUT_S OUT_H LIBGTK: one x86_64 trampoline per intercepted function for libatl_threadcheck.so.
# The GTK/GDK/GSK functions are all functions libgtk-4 exports; Wayland and EGL are the fixed list below (the
# calls whose arguments threadcheck.c inspects).
import subprocess
import sys

WAYLAND_EGL = [
	'wl_display_dispatch', 'wl_display_dispatch_pending', 'wl_display_roundtrip', 'wl_display_prepare_read',
	'wl_display_dispatch_queue', 'wl_display_dispatch_queue_pending', 'wl_display_roundtrip_queue',
	'wl_display_prepare_read_queue',
	'wl_proxy_marshal_flags', 'wl_proxy_marshal_array_flags', 'wl_proxy_marshal_constructor',
	'wl_proxy_marshal_constructor_versioned', 'wl_proxy_marshal_array_constructor',
	'wl_proxy_marshal_array_constructor_versioned', 'wl_proxy_add_listener', 'wl_proxy_add_dispatcher',
	'wl_egl_window_resize', 'wl_egl_window_destroy',
	'eglMakeCurrent', 'eglSwapBuffers', 'eglCreateWindowSurface', 'eglCreatePlatformWindowSurface',
	'eglDestroySurface',
]

out_s, out_h, libgtk = sys.argv[1:4]
nm = subprocess.run(['nm', '-D', '--defined-only', libgtk], check=True, capture_output=True, text=True).stdout
names = sorted({l.split()[2] for l in nm.splitlines()
                if len(l.split()) == 3 and l.split()[1] in ('T', 'i') and l.split()[2].startswith(('gtk_', 'gdk_', 'gsk_'))})
names += WAYLAND_EGL

with open(out_s, 'w') as f:
	f.write('/* generated by gen_trampolines.py */\n\t.text\n')
	for i, n in enumerate(names):
		f.write(f'\t.globl {n}\n\t.type {n}, @function\n{n}:\n\tmovl ${i}, %r11d\n\tjmp tc_entry\n\t.size {n}, .-{n}\n')
	f.write('\t.section .note.GNU-stack,"",@progbits\n')
with open(out_h, 'w') as f:
	f.write('/* generated by gen_trampolines.py */\n#define TC_N %d\nstatic const char *const tc_names[TC_N] = {\n' % len(names))
	f.write(''.join(f'\t"{n}",\n' for n in names))
	f.write('};\n')
